-- Freeze the exact v6.7 policy that was active at migration time. Historical outcomes are
-- intentionally not a validation cohort: they were generated by several different engines.
insert into public.lob_policy_versions (
  status,
  engine_version,
  fingerprint,
  source_online_version,
  source_pattern_profile_id,
  online_profiles,
  pattern_profile,
  confirmed_at,
  decision_reason
)
select
  'CHAMPION',
  '6.7.0-ONLINE-COIN-LEARNING',
  md5(
    coalesce((
      select jsonb_agg(to_jsonb(p) order by p.exchange, p.market, p.pattern)::text
        from public.lob_market_profiles p
    ), '[]') ||
    coalesce((
      select to_jsonb(lp)::text
        from public.lob_learning_profiles lp
       where lp.active
       order by lp.generated_at desc
       limit 1
    ), 'null')
  ),
  coalesce((
    select sum(p.version)
      from public.lob_market_profiles p
     where p.market = '*'
  ), 0),
  (
    select lp.id
      from public.lob_learning_profiles lp
     where lp.active
     order by lp.generated_at desc
     limit 1
  ),
  coalesce((
    select jsonb_agg(to_jsonb(p) order by p.exchange, p.market, p.pattern)
      from public.lob_market_profiles p
  ), '[]'::jsonb),
  (
    select to_jsonb(lp)
      from public.lob_learning_profiles lp
     where lp.active
     order by lp.generated_at desc
     limit 1
  ),
  now(),
  'INITIAL_V670_POLICY_FROZEN'
where not exists (
  select 1 from public.lob_policy_versions where status = 'CHAMPION'
);

