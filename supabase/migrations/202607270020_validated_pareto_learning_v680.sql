-- Trading-booooo v6.8.0-VALIDATED-PARETO-LEARNING
--
-- Raw outcomes still update after every live close, but they are observations rather than
-- production releases. A frozen champion and a frozen alternate are assigned whole scan
-- cycles at normal size. Promotion requires contemporaneous live evidence that net return
-- AND win rate improve while completed-trade supply, slot turnover, capital turnover and
-- notional do not fall. The promoted model is provisional until it repeats that dominance
-- against the old champion as a live control; otherwise it is rolled back.

create table if not exists public.lob_policy_versions (
  version bigint generated by default as identity primary key,
  status text not null check (
    status in (
      'CHAMPION',
      'CHALLENGER',
      'CONTROL',
      'REJECTED',
      'RETIRED',
      'ROLLED_BACK'
    )
  ),
  parent_version bigint references public.lob_policy_versions(version),
  engine_version text not null,
  fingerprint text not null unique,
  source_online_version bigint not null default 0,
  source_pattern_profile_id uuid references public.lob_learning_profiles(id) on delete set null,
  online_profiles jsonb not null default '[]'::jsonb,
  pattern_profile jsonb,
  traffic_fraction numeric not null default 0.5
    check (traffic_fraction >= 0 and traffic_fraction <= 0.5),
  criteria jsonb not null default jsonb_build_object(
    'min_samples_per_arm', 40,
    'early_stop_samples_per_arm', 20,
    'max_samples_per_arm', 120,
    'confidence', 0.90,
    'min_notional_ratio', 0.98,
    'min_common_mix_coverage', 0.80,
    'requires_positive_net_after_costs', true,
    'requires_win_rate_improvement', true,
    'requires_exchange_pattern_mix_adjustment', true,
    'requires_trade_rate_non_decrease', true,
    'requires_capital_turnover_non_decrease', true
  ),
  metrics jsonb not null default '{}'::jsonb,
  decision_reason text,
  evaluation_started_at timestamptz,
  promoted_at timestamptz,
  confirmed_at timestamptz,
  evaluated_at timestamptz,
  retired_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists lob_policy_versions_single_champion_idx
  on public.lob_policy_versions ((1))
  where status = 'CHAMPION';

create unique index if not exists lob_policy_versions_single_alternate_idx
  on public.lob_policy_versions ((1))
  where status in ('CHALLENGER', 'CONTROL');

create index if not exists lob_policy_versions_status_idx
  on public.lob_policy_versions(status, version desc);

