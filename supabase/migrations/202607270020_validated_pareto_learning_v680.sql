-- Existing rows remain LEGACY and cannot vote in a promotion. Monetary fields are filled
-- only for diagnostics and cohort-independent historical analysis.
update public.lob_online_outcomes o
set realized_cost_quote = greatest(0, coalesce(p.realized_cost_quote, 0)),
    capital_seconds = greatest(0, coalesce(p.realized_cost_quote, 0)) *
      greatest(0, o.held_seconds),
    engine_version = p.metadata ->> 'engine_version'
from public.trading_positions p
where p.id = o.position_id
  and o.policy_version is null;

create or replace function public.enrich_lob_online_outcome_policy()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_metadata jsonb;
  v_cost numeric;
  v_version_text text;
  v_version bigint;
  v_lane text;
begin
  select coalesce(p.metadata, '{}'::jsonb), greatest(0, coalesce(p.realized_cost_quote, 0))
    into v_metadata, v_cost
    from public.trading_positions p
   where p.id = new.position_id;

  v_version_text := v_metadata #>> '{lob_signal,policy,version}';
  if coalesce(v_version_text, '') ~ '^[0-9]+$' then
    v_version := v_version_text::bigint;
    if not exists (
      select 1 from public.lob_policy_versions p where p.version = v_version
    ) then
      v_version := null;
    end if;
  end if;
  v_lane := upper(coalesce(
    nullif(v_metadata #>> '{lob_signal,policy,lane}', ''),
    'LEGACY'
  ));
  if v_lane not in ('CHAMPION', 'CHALLENGER', 'CONTROL') then
    v_lane := 'LEGACY';
  end if;

  new.policy_version := v_version;
  new.policy_lane := v_lane;
  new.realized_cost_quote := v_cost;
  new.capital_seconds := v_cost * greatest(0, new.held_seconds);
  new.engine_version := nullif(v_metadata ->> 'engine_version', '');
  return new;
end;
$$;

